import { createRequire } from 'node:module';
const req = createRequire(new URL('../../../apps/parlor/package.json', import.meta.url));
const { io } = req('socket.io-client');
const s = io('http://localhost:' + process.env.PORT, { transports: ['websocket'], reconnection: false });
const ack = (ev, ...a) => new Promise((r) => s.emit(ev, ...a, (...x) => r(x)));
const wait = (ms) => new Promise(r => setTimeout(r, ms));
let last; const log = [];
s.on('game:state', (v) => { last = v; const k = `${v.phase}/active=${v.activePlayerIndex}(${v.players[v.activePlayerIndex].isBot?'bot':'me'})`; if (log.at(-1) !== k) log.push(k);
  if (v.isActivePlayer && v.phase === 'rolling') s.emit('game:action', { type: 'roll-dice' });
  if (v.phase === 'phase1' && !v.players[v.myIndex].phase1Submitted) s.emit('game:action', { type: 'phase1-pass' });
  if (v.phase === 'phase2' && v.isActivePlayer) s.emit('game:action', { type: 'phase2-pass' });
});
s.on('error', (m) => console.log('error', m));
await wait(300);
await ack('lobby:create', 'Host'); await ack('lobby:selectGame', 'quixx');
await ack('lobby:addBot'); await ack('lobby:addBot');
await ack('lobby:ready', true); console.log('start', await ack('lobby:startGame'));
await wait(15000);
console.log(log.join('\n')); console.log('FINAL', log.at(-1)); process.exit(0);
